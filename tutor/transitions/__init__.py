"""State transition registry — one data row per graph node (ticket #8, #25).

This package is the single source of state-transition mechanics for the
scenario: 44 rows, one per graph node — a ``(base state, level)`` pair
(ADR-0006, spec #16 C1-9). :data:`ROW_REGISTRY` is the row storage of
record; the row-resolution seam :func:`row_for` looks rows up by pair
with the session's level.

Each row lives in its own module, one per base state. The row schema,
the closed sets, :func:`validate_transitions` and
:func:`axis_copy_violations` live in :mod:`tutor.transitions._validate`
and are re-exported here.

Spec #16 C1-1 (ticket #17) added :data:`ROW_REGISTRY` and the
:func:`row_for` seam as the EXPAND step: the table expanded 1:1 to
pair keys alongside the suffix-name keys. Spec #16 C1-2..C1-7
(tickets #18-#23) folded each triplet into one axis module keyed by
bare level, with :func:`with_fixture_level` generating the fixtures.
Spec #16 C1-8 (ticket #24) made registration the point of no return.

Spec #16 C1-9 (ticket #25) is the CONTRACT: the suffix-name storage,
the expand step (:func:`expand_rows`), the join (:func:`join_state`)
and the flat-table row generator (:func:`axis_rows`) are deleted. The
assembly keys the pairs directly — single-form modules contribute
``(BASE, None)``, axis modules contribute ``(BASE, level)`` from a
level-keyed row map (:func:`axis_pairs`) — every target in the graph
spells a base name, and the scenario keys its states by base name
under the same algebra (ADR-0006 decision 4).
"""

